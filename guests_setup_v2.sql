create table if not exists public.guests (
  id          bigint generated always as identity primary key,
  sort_order  double precision not null default 0,
  flat        text not null,
  type        text not null default 'Rented Flat',
  name        text not null default '',
  contact     text not null default '',
  rent        text not null default '',
  deposit     text not null default '',
  payment     text not null default 'Not Updated',
  created_at  timestamptz not null default now()
);
create index if not exists guests_sort_idx on public.guests (sort_order, id);

-- Needed so a deleted guest can be restored with the same id
alter table public.guests alter column id set generated by default;

-- ===== Full change history (every insert / update / delete) =====
create table if not exists public.guest_history (
  id          bigint generated always as identity primary key,
  guest_id    bigint not null,
  op          text not null,              -- INSERT | UPDATE | DELETE
  old_row     jsonb,
  new_row     jsonb,
  changed_by  text,
  changed_at  timestamptz not null default now()
);
create index if not exists guest_history_time_idx on public.guest_history (changed_at desc, id desc);

create or replace function public.log_guest_change() returns trigger
language plpgsql security definer set search_path = public as $$
declare who text := coalesce(auth.jwt() ->> 'email', current_user);
begin
  if tg_op = 'INSERT' then
    insert into guest_history(guest_id, op, old_row, new_row, changed_by)
    values (new.id, 'INSERT', null, to_jsonb(new), who);
  elsif tg_op = 'UPDATE' then
    if to_jsonb(old) is distinct from to_jsonb(new) then
      insert into guest_history(guest_id, op, old_row, new_row, changed_by)
      values (new.id, 'UPDATE', to_jsonb(old), to_jsonb(new), who);
    end if;
  else
    insert into guest_history(guest_id, op, old_row, new_row, changed_by)
    values (old.id, 'DELETE', to_jsonb(old), null, who);
  end if;
  return null;
end $$;

drop trigger if exists guests_audit on public.guests;
create trigger guests_audit after insert or update or delete on public.guests
  for each row execute function public.log_guest_change();

-- ===== Security: only logged-in staff =====
alter table public.guests        enable row level security;
alter table public.guest_history enable row level security;

drop policy if exists "staff read"   on public.guests;
drop policy if exists "staff insert" on public.guests;
drop policy if exists "staff update" on public.guests;
drop policy if exists "staff delete" on public.guests;
create policy "staff read"   on public.guests for select to authenticated using (true);
create policy "staff insert" on public.guests for insert to authenticated with check (true);
create policy "staff update" on public.guests for update to authenticated using (true) with check (true);
create policy "staff delete" on public.guests for delete to authenticated using (true);

-- History is read-only for the app: nobody can edit or erase it from the website
drop policy if exists "staff read history" on public.guest_history;
create policy "staff read history" on public.guest_history for select to authenticated using (true);
